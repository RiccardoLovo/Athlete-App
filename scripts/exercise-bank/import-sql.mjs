// Emits idempotent SQL that syncs data/exercise-bank/*.json into the database.
//
// The JSON stays the source of truth: this is a projection of it, re-runnable
// after any workbook edit. It is set-based through a temp table rather than a
// statement per exercise, so the whole sync is one transaction.
//
// Safe on the exercises already in the app:
//  * An existing row is matched by bank_id, else by normalized name, and then
//    only LINKED and annotated. Its name, discipline, category, body_region
//    and muscle_group are left exactly as the coach set them.
//  * Nothing is ever deleted from exercises.
//
//   node scripts/exercise-bank/import-sql.mjs > /tmp/import.sql
import { readFileSync, readdirSync } from "node:fs";

const DIR = "data/exercise-bank/";
const blocks = readdirSync(DIR).filter((f) => f.endsWith(".json")).sort()
  .map((f) => JSON.parse(readFileSync(DIR + f, "utf8")));
const EX = blocks.flatMap((b) => b.exercises);
const EDGES = blocks.flatMap((b) => b.swap_edges);

const q = (v) => v == null || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`;
const arr = (a) => !a || !a.length ? "'{}'::text[]"
  : `ARRAY[${a.map((x) => q(x)).join(",")}]::text[]`;
const norm = (s) => (s || "").toLowerCase().replace(/[^a-z0-9]/g, "");

// Keep the app's existing axes populated for new rows so the current UI, which
// still reads discipline/category/body_region/muscle_group, shows them sensibly.
const BLOCK_CLASS = {
  "01-lower-body-plyometrics": ["Strength", "Plyometric"],
  "02-lower-body-strength": ["Strength", "Resistance"],
  "03-upper-body-push": ["Strength", "Resistance"],
  "04-upper-body-pull": ["Strength", "Resistance"],
  "05-trunk": ["Strength", "Resistance"],
  "06-carries": ["Strength", "Resistance"],
  "07-prep-prehab": ["Strength", "Activation"],
  "08-power-olympic": ["Strength", "Resistance"],
  "09-run-mechanics": ["Running", "Activation"],
};

function bodyRegion(pattern) {
  if (/anti-|^trunk /.test(pattern)) return "Core";
  if (/carry/.test(pattern)) return "Full Body";
  if (/push|pull|elbow|shoulder|scapular/.test(pattern)) return "Upper Body";
  return "Lower Body";
}

const out = [];
out.push("-- Generated by scripts/exercise-bank/import-sql.mjs — do not hand-edit.");
out.push(`-- ${EX.length} exercises, ${EDGES.length} swap edges, ${blocks.length} blocks.`);
out.push("BEGIN;");
out.push(`
CREATE TEMP TABLE bank_import (
  bank_id text PRIMARY KEY, norm_name text NOT NULL, name text NOT NULL,
  block text, family text, modifiers text[], movement_pattern text, plane text,
  stance text, per_side boolean, ssc text, ground_contact text, velocity text,
  joint_actions text[], agonists text[], synergists text[], stabilizers text[],
  position_note text, resistance_note text, length_bias text,
  admissible_intents text[], dose_window text,
  s_axial text, s_flexion text, s_impact text, s_landing text,
  s_achilles text, s_knee text, s_shoulder text, s_elbow text,
  equipment text[], equip_tier text, space_required text, skill_level text,
  cues text[], video_url text, video_source text,
  discipline text, category text, body_region text, muscle_group text
) ON COMMIT DROP;`);

const rows = EX.map((e) => {
  const [disc, cat] = BLOCK_CLASS[e.block] ?? ["Strength", "Resistance"];
  const st = e.stress;
  return "(" + [
    q(e.id), q(norm(e.name)), q(e.name),
    q(e.block), q(e.family), arr(e.modifiers), q(e.pattern), q(e.plane),
    q(e.stance), e.perSide ? "true" : "false", q(e.ssc), q(e.gct), q(e.velocity),
    arr(e.joints), arr(e.agonists), arr(e.synergists), arr(e.stabilizers),
    q(e.position), q(e.resistance), q(e.lengthBias),
    arr(e.intents), q(e.dose),
    q(st.axial), q(st.flexion), q(st.impact), q(st.landing),
    q(st.achilles), q(st.knee), q(st.shoulder), q(st.elbow),
    arr(e.equipment), q(e.equipTier), q(e.space), q(e.skill),
    arr(e.cues),
    q(e.video ? `https://www.youtube.com/watch?v=${e.video.id}` : null),
    q(e.video ? e.video.author : null),
    q(disc), q(cat), q(bodyRegion(e.pattern)),
    q((e.agonists || []).join(", ") || null),
  ].join(",") + ")";
});
out.push("INSERT INTO bank_import VALUES\n" + rows.join(",\n") + ";");

out.push(`
-- 1. Link rows the app already has, by name. Their own classification is left
--    untouched — only the bank key is attached.
UPDATE public.exercises e
   SET bank_id = b.bank_id
  FROM bank_import b
 WHERE e.bank_id IS NULL
   AND lower(regexp_replace(e.name_en, '[^a-zA-Z0-9]', '', 'g')) = b.norm_name;`);

out.push(`
-- 2. Insert the rest.
INSERT INTO public.exercises
  (name_en, name_it, discipline, category, body_region, muscle_group,
   is_global, structure_type, video_url, bank_id)
SELECT b.name, b.name, b.discipline, b.category, b.body_region, b.muscle_group,
       true, 'simple', b.video_url, b.bank_id
  FROM bank_import b
 WHERE NOT EXISTS (SELECT 1 FROM public.exercises e WHERE e.bank_id = b.bank_id);`);

out.push(`
-- 3. Annotation, upserted.
INSERT INTO public.exercise_annotations AS a (
  exercise_id, block, family, modifiers, movement_pattern, plane, stance,
  per_side, ssc, ground_contact, velocity, joint_actions, agonists, synergists,
  stabilizers, position_note, resistance_note, length_bias, admissible_intents,
  dose_window, stress_axial, stress_flexion, stress_impact, stress_landing,
  stress_achilles, stress_knee, stress_shoulder, stress_elbow, equipment,
  equip_tier, space_required, skill_level, cues, video_source, video_verified_at)
SELECT e.id, b.block, b.family, b.modifiers, b.movement_pattern, b.plane, b.stance,
       b.per_side, b.ssc, b.ground_contact, b.velocity, b.joint_actions, b.agonists,
       b.synergists, b.stabilizers, b.position_note, b.resistance_note, b.length_bias,
       b.admissible_intents, b.dose_window, b.s_axial, b.s_flexion, b.s_impact,
       b.s_landing, b.s_achilles, b.s_knee, b.s_shoulder, b.s_elbow, b.equipment,
       b.equip_tier, b.space_required, b.skill_level, b.cues, b.video_source,
       CASE WHEN b.video_source IS NOT NULL THEN now() ELSE NULL END
  FROM bank_import b JOIN public.exercises e ON e.bank_id = b.bank_id
ON CONFLICT (exercise_id) DO UPDATE SET
  block = EXCLUDED.block, family = EXCLUDED.family, modifiers = EXCLUDED.modifiers,
  movement_pattern = EXCLUDED.movement_pattern, plane = EXCLUDED.plane,
  stance = EXCLUDED.stance, per_side = EXCLUDED.per_side, ssc = EXCLUDED.ssc,
  ground_contact = EXCLUDED.ground_contact, velocity = EXCLUDED.velocity,
  joint_actions = EXCLUDED.joint_actions, agonists = EXCLUDED.agonists,
  synergists = EXCLUDED.synergists, stabilizers = EXCLUDED.stabilizers,
  position_note = EXCLUDED.position_note, resistance_note = EXCLUDED.resistance_note,
  length_bias = EXCLUDED.length_bias, admissible_intents = EXCLUDED.admissible_intents,
  dose_window = EXCLUDED.dose_window,
  stress_axial = EXCLUDED.stress_axial, stress_flexion = EXCLUDED.stress_flexion,
  stress_impact = EXCLUDED.stress_impact, stress_landing = EXCLUDED.stress_landing,
  stress_achilles = EXCLUDED.stress_achilles, stress_knee = EXCLUDED.stress_knee,
  stress_shoulder = EXCLUDED.stress_shoulder, stress_elbow = EXCLUDED.stress_elbow,
  equipment = EXCLUDED.equipment, equip_tier = EXCLUDED.equip_tier,
  space_required = EXCLUDED.space_required, skill_level = EXCLUDED.skill_level,
  cues = EXCLUDED.cues, video_source = EXCLUDED.video_source,
  video_verified_at = EXCLUDED.video_verified_at;`);

// Flags
out.push(`
CREATE TEMP TABLE bank_flags (bank_id text, field text, kind text, note text) ON COMMIT DROP;`);
const flagRows = EX.flatMap((e) => (e.flags || []).map((f) =>
  `(${q(e.id)},${q(f.field)},${q(f.kind)},${q(f.text)})`));
if (flagRows.length) {
  out.push("INSERT INTO bank_flags VALUES\n" + flagRows.join(",\n") + ";");
  out.push(`
DELETE FROM public.exercise_annotation_flags f
 USING public.exercises e
 WHERE f.exercise_id = e.id AND e.bank_id IS NOT NULL;
INSERT INTO public.exercise_annotation_flags (exercise_id, field, kind, note)
SELECT e.id, b.field, b.kind, b.note
  FROM bank_flags b JOIN public.exercises e ON e.bank_id = b.bank_id
ON CONFLICT (exercise_id, field, kind) DO UPDATE SET note = EXCLUDED.note;`);
}

// Swap edges — inserted after annotations so the safety trigger can evaluate them.
out.push(`
CREATE TEMP TABLE bank_edges (from_bank text, to_bank text, reason text,
  same_text text, changed_text text, dose_text text) ON COMMIT DROP;`);
out.push("INSERT INTO bank_edges VALUES\n" + EDGES.map((e) =>
  `(${q(e.from)},${q(e.to)},${q(e.reason)},${q(e.same)},${q(e.changed)},${q(e.dose)})`
).join(",\n") + ";");
out.push(`
DELETE FROM public.exercise_swaps s
 USING public.exercises e
 WHERE s.from_exercise_id = e.id AND e.bank_id IS NOT NULL;
INSERT INTO public.exercise_swaps
  (from_exercise_id, to_exercise_id, reason, same_text, changed_text, dose_text)
SELECT f.id, t.id, b.reason, b.same_text, b.changed_text, b.dose_text
  FROM bank_edges b
  JOIN public.exercises f ON f.bank_id = b.from_bank
  JOIN public.exercises t ON t.bank_id = b.to_bank;`);

out.push(`
-- What landed.
SELECT
  (SELECT count(*) FROM public.exercises WHERE bank_id IS NOT NULL) AS linked_exercises,
  (SELECT count(*) FROM public.exercise_annotations) AS annotations,
  (SELECT count(*) FROM public.exercise_swaps) AS swaps,
  (SELECT count(*) FROM public.exercise_annotation_flags) AS flags,
  (SELECT count(*) FROM public.exercises) AS exercises_total;`);
out.push("COMMIT;");

process.stdout.write(out.join("\n") + "\n");
